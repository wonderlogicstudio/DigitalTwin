class _SafeFormatDict(UserDict[str, object]):
    def __missing__(self, key: str) -> str:
        return "{" + key + "}"


def normalize_language(language: str | None = None) -> str:
    """Return a supported language code, falling back to Korean."""

    if language in SUPPORTED_LANGUAGES:
        return str(language)
    return DEFAULT_LANGUAGE


def get_supported_languages() -> dict[str, str]:
    """Return supported language codes and display names."""

    return dict(SUPPORTED_LANGUAGES)


def get_language_display_name(language: str | None) -> str:
    """Return the display name for a language code."""

    return SUPPORTED_LANGUAGES.get(normalize_language(language), SUPPORTED_LANGUAGES[DEFAULT_LANGUAGE])


def t(key: str, language: str = DEFAULT_LANGUAGE, **kwargs: object) -> str:
    """Look up and safely format a user-facing translation string."""

    language_code = normalize_language(language)
    template = TRANSLATIONS.get(language_code, {}).get(key)
    if template is None:
        template = TRANSLATIONS[DEFAULT_LANGUAGE].get(key, key)
    if not kwargs:
        return template
    try:
        return template.format_map(_SafeFormatDict(kwargs))
    except (KeyError, IndexError, ValueError):
        return template


def validate_translation_keys() -> list[str]:
    """Return missing translation keys across supported languages."""

    expected = set(TRANSLATIONS[DEFAULT_LANGUAGE])
    missing: list[str] = []
    for language in SUPPORTED_LANGUAGES:
        keys = set(TRANSLATIONS.get(language, {}))
        for key in sorted(expected - keys):
            missing.append(f"{language}:{key}")
    return missing
