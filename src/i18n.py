class _SafeFormatDict(UserDict[str, object]):
    def __missing__(self, key: str) -> str:
        return "{" + key + "}"


def normalize_language(language: str | None = None) -> str:
    """Return a supported language code, falling back to Korean."""

    if language in SUPPORTED_LANGUAGES:
        return str(language)
    return DEFAULT_LANGUAGE


def get_supported_languages() -> dict[str, str]:
    """Return supported language codes and display names."""

    return dict(SUPPORTED_LANGUAGES)


def get_language_display_name(language: str | None) -> str:
    """Return the display name for a language code."""

    return SUPPORTED_LANGUAGES.get(normalize_language(language), SUPPORTED_LANGUAGES[DEFAULT_LANGUAGE])


